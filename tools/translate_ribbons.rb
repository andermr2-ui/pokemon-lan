path = "Data/messages_es_core.dat"
data = Marshal.load(File.binread(path))

missing = []
[[25, NAMES_ES], [26, DESCRIPTIONS_ES]].each do |cat, dict|
  hash = data[cat]
  raise "cat#{cat} no es un Hash" unless hash.is_a?(Hash)
  dict.each do |eng, esp|
    if !hash.key?(eng)
      missing << [cat, eng]
      next
    end
    hash[eng] = esp
  end
end

if !missing.empty?
  puts "AVISO: #{missing.length} claves no encontradas en el diccionario original:"
  missing.each { |cat, eng| puts "  cat#{cat}: #{eng.inspect}" }
  raise "abortando, revisar claves"
end

unmatched_25 = data[25].keys - NAMES_ES.keys
unmatched_26 = data[26].keys - DESCRIPTIONS_ES.keys
puts "cat25 sin traducir: #{unmatched_25.length} #{unmatched_25.inspect}" unless unmatched_25.empty?
puts "cat26 sin traducir: #{unmatched_26.length} #{unmatched_26.inspect}" unless unmatched_26.empty?

File.open(path + ".bak_before_ribbon_translation", "wb") { |f| f.write(File.binread(path)) } unless File.exist?(path + ".bak_before_ribbon_translation")
File.open(path, "wb") { |f| Marshal.dump(data, f) }
puts "OK: #{NAMES_ES.length} nombres y #{DESCRIPTIONS_ES.length} descripciones de cintas traducidas en #{path}"
